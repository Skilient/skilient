// Collects every `it.todo("...")` in services/*/test/journeys: the parts of the end-to-end specs a service
// journey cannot check (web pages, or another workstream's service). Each starts with the workstream that owes it.
// Usage: node tools/lint/src/journey-todos.mjs > docs/azure/journey-handoff.md
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export function collectTodos(root) {
  const out = [];
  const services = join(root, "services");
  for (const service of readdirSync(services).sort()) {
    const dir = join(services, service, "test", "journeys");
    if (!existsSync(dir)) continue;
    for (const file of readdirSync(dir).filter((f) => f.endsWith(".test.ts")).sort()) {
      const text = readFileSync(join(dir, file), "utf8");
      for (const m of text.matchAll(/it\.todo\(\s*"((?:[^"\\]|\\.)*)"/g)) {
        const item = m[1].replace(/\\"/g, '"');
        const owner = /^(W\d+)/.exec(item)?.[1] ?? "unassigned";
        out.push({ service, file: `services/${service}/test/journeys/${file}`, owner, item });
      }
    }
  }
  return out;
}

export function renderHandoff(todos) {
  const byOwner = new Map();
  for (const t of todos) byOwner.set(t.owner, [...(byOwner.get(t.owner) ?? []), t]);
  const owners = [...byOwner.keys()].sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)));
  const lines = [
    "# Journey handoff: spec parts the service journeys cannot check",
    "",
    "Generated by `node tools/lint/src/journey-todos.mjs` from the `it.todo` entries in `services/*/test/journeys`; `tools/lint/test/journey-todos.test.ts` fails when this file misses one. Each item is owed by the workstream it names (W13: the web app, once it calls the new services).",
    "",
  ];
  for (const owner of owners) {
    lines.push(`## ${owner}`, "");
    for (const t of byOwner.get(owner)) lines.push(`- ${t.item} (\`${t.file}\`)`);
    lines.push("");
  }
  return lines.join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = resolve(process.argv[2] ?? join(import.meta.dirname, "../../.."));
  process.stdout.write(renderHandoff(collectTodos(root)));
}
