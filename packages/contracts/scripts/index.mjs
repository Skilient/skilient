// Writes gen/index.ts: every service descriptor the contracts define, so tools
// (the budget check, the host) can list them. Run by `pnpm gen` after buf generate.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const gen = join(import.meta.dirname, "..", "gen");

function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? files(join(dir, d.name)) : d.name.endsWith("_pb.ts") ? [join(dir, d.name)] : [],
  );
}

const imports = [];
const names = [];
for (const file of files(gen).sort()) {
  const source = readFileSync(file, "utf8");
  for (const m of source.matchAll(/^export const (\w+Service): GenService</gm)) {
    const alias = `${m[1]}_${names.length}`;
    const path = "./" + relative(gen, file).replace(/\\/g, "/").replace(/\.ts$/, "");
    imports.push(`import { ${m[1]} as ${alias} } from "${path}";`);
    names.push(alias);
  }
}

writeFileSync(
  join(gen, "index.ts"),
  `// Generated by scripts/index.mjs. Do not edit.\nimport type { DescService } from "@bufbuild/protobuf";\n${imports.join("\n")}\n\nexport const allServices: readonly DescService[] = [${names.join(", ")}];\n`,
);
