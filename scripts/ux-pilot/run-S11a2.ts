/** S11 part a2: T113 staff and change notice (tabs by URL), T114 cancel a paid event. */
import { launch, context, page, ready, signIn, accounts } from "./lib/browser.ts";
import { timedClick, setTask, timedGoto } from "./lib/timed.ts";
import { shot } from "./lib/shot.ts";
import { sql, mainText, dialogText, toastText } from "./lib/act.ts";
const say = (...x: unknown[]) => console.log(...x);
const A = accounts(); const acc = A.accounts; const ev = A.ids.events;
const T = (t: any) => `${t.kind} pending=${t.pendingMs} result=${t.resultMs} "${String(t.shown).replace(/\n/g, " ").slice(0, 160)}"`;
const b = await launch(); const p = await page(await context(b, { device: "phone" }));
p.on("dialog", async (d) => { say("   native dialog:", d.message()); await d.accept(); });
await signIn(p, acc.officer1); await ready(p, 500);
const M = p.locator("main");
const tail = async (n = 700) => (await mainText(p, 4000)).split("Close-out | Feedback | ")[1]?.slice(0, n);
setTask("T113");
const [m] = await sql`select id from public.events where title = '[UX test] Manual approval meetup'`;
await timedGoto(p, `/events/${m.id}/manage?tab=staff`); await ready(p, 600);
say("T113 staff:", await tail(300));
await M.getByLabel("Username").fill("uxp_helper_d");
say("T113 add staff:", T(await timedClick(p, M.getByRole("button", { name: "Add staff" }), "add check-in staff")), await toastText(p), await tail(300));
await timedGoto(p, `/events/${m.id}/manage?tab=messages`); await ready(p, 600);
say("T113 messages:", await tail(500));
await M.getByLabel("Message").fill("Venue change: we've moved to CS Lab 1, same time.");
say("T113 send:", T(await timedClick(p, M.getByRole("button", { name: "Send to everyone registered" }), "send change notice")), await toastText(p), await tail(300));
await shot(p, "T113");
const t = await page(await context(b, { device: "phone", throttle: false })); await signIn(t, acc.helperB); await t.goto("/notifications"); await ready(t, 500);
say("T113 registrant bell:", (await mainText(t, 2000)).split(" | ").filter((l) => /Lab 1|venue|Manual/i.test(l)).slice(0, 3));
await t.context().close();
setTask("T114");
await timedGoto(p, `/events/${ev.paid}/manage?tab=messages`); await ready(p, 600);
await M.getByText("Cancel the event").first().click(); await p.waitForTimeout(500);
say("T114 cancel section:", (await mainText(p, 5000)).split("Cancel the event | ")[1]?.slice(0, 300));
await M.getByLabel(/Why/).fill("The trainer is ill. We'll send your PKR 100 back by JazzCash this week.");
say("T114 cancel:", T(await timedClick(p, M.getByTestId("cancel-event").getByRole("button", { name: "Cancel the event" }).or(M.getByRole("button", { name: "Cancel the event" })).first(), "cancel paid event", { timeout: 30_000 })), await toastText(p));
await p.waitForTimeout(1200); await ready(p, 500);
say("T114 after:", (await mainText(p, 1500)).slice(0, 500));
await timedGoto(p, `/events/${ev.paid}/manage?tab=payments`); await ready(p, 600);
say("T114 payments after cancel:", (await tail(700)));
await shot(p, "T114");
const s = await page(await context(b, { device: "phone", throttle: false })); await signIn(s, acc.helperB); await s.goto(`/events/${ev.paid}/ticket`); await ready(s, 500);
say("T114 paid student's ticket:", (await mainText(s, 2000)).slice(0, 600));
await b.close(); await sql.end();
