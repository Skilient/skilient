import { launch, context, page, ready, signIn, accounts } from "./lib/browser.ts";
import { timedClick, setTask } from "./lib/timed.ts";
import { sql, mainText, dialogText, toastText } from "./lib/act.ts";
import { shot } from "./lib/shot.ts";
setTask("T077");
const A = accounts(); const b = await launch(); const p = await page(await context(b, { device: "phone" }));
await signIn(p, A.accounts.tester);
const [sw] = await sql`select id from public.swaps where learner_id = ${A.accounts.tester.id} order by requested_at desc limit 1`;
await p.goto("/swaps/" + sw.id); await ready(p, 600);
p.on("dialog", async (d) => { console.log("native dialog:", d.type(), d.message()); await d.accept(); });
console.log("end swap element:", await p.getByRole("button", { name: "End swap" }).evaluate((e) => e.outerHTML.slice(0, 300)));
const t = await timedClick(p, p.getByRole("button", { name: "End swap" }), "End swap");
await p.waitForTimeout(800);
console.log("end:", t.kind, t.resultMs, "| dialog:", await dialogText(p, 600));
const c = p.locator('[role="dialog"], [role="alertdialog"]').getByRole("button", { name: /End/ }).last();
if (await c.isVisible().catch(() => false)) console.log("confirm:", (await timedClick(p, c, "confirm end swap")).resultMs, await toastText(p));
await p.waitForTimeout(1500);
console.log("after:", await mainText(p, 700));
await shot(p, "T077");
console.log("teacher entries:", JSON.stringify(await sql`select kind::text, status::text from public.record_entries where user_id = ${A.accounts.helperA.id} and kind::text like '%taught%'`));
const q = await page(await context(b, { device: "phone", throttle: false })); await signIn(q, A.accounts.helperA); await q.goto("/profile/uxp_helper_a"); await ready(q, 500);
console.log("teacher profile:", (await mainText(q, 1500)).split(" | ").filter((l) => /Taught|thank|Swap|SQL/i.test(l)).slice(0, 8));
await q.goto("/me/record"); await ready(q, 500); console.log("teacher record:", (await mainText(q, 600)));
await b.close(); await sql.end();
